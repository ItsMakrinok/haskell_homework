{-
1. Вводится конечная последовательность из n натуральных чисел (начиная с нуля).

Например,
list = [23,7,44,5,1,5,2,8,11,3,7,6,0,9]
или
list2 = [0..1000]

Необходимо определить наименьшее натуральное число (начиная с нуля), отсутствующее в последовательности.
Задать реализующую функцию с сигнатурой (проверку на положительность элементов списка не делать):

f1 :: [Int] -> Int
-}



f1 :: [Int] -> Int
f1 xs = head [n | n <- [0..], notElem n xs]


list = [23,7,44,5,1,5,2,8,11,3,7,6,0,9]
list2 = [0..1000]

main = do
    print(f1 list)
    print(f1 list2)
