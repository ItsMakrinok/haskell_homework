{-
1. Для произвольного конечного списка (элементы которого лежат в классе Eq) сделать проверку, что все элементы равны. Проверка должна прерываться на первом же нарушении.
Сама проверка должна быть функцией, принимающей список и возвращающей булево значение.
-}


allEqual [] = True
allEqual [_] = True
allEqual (x:y:xs) = x == y && allEqual (y:xs)

main = do
    print (allEqual [1,1,1,1])
    print (allEqual [1,2,1])
