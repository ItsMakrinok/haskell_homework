{-
6. для произвольного конечного (не пустого) списка пар координат точек плоскости
(например,  [((-5.23),4.2),(2.456,13.234),(11241,211.2),((-1),0)])
найти наименьшее расстояние между всеми возможными парами точек из списка.
-}


mindist ps = minimum (list ps)
  where
    list [] = []
    list (p:ps) = [dist p q | q <- ps] ++ list ps

    dist (x1,y1) (x2,y2) = sqrt ((x1-x2)^2 + (y1-y2)^2)

test1 = [((-5.23),4.2),(2.456,13.234),(11241,211.2),((-1),0)]
test2 = [(1, 2), (2, 3), (2, 5), (3, 2)]
test3 = [(0, 1), (1, 0), (1, 1), (0, 0)]

main = do
    print(mindist test1)
    print(mindist test2)
    print(mindist test3)

